// ==========================================
// Exercise 2.4 - Arithmetic Operators
// ==========================================

let x = 7;
let y = 3;

// Addition
console.log(x + y); // 10

// Subtraction
console.log(x - y); // 4

// Multiplication
console.log(x * y); // 21

// Division
console.log(x / y); // 2.3333333333333335

// Modulus - remainder
console.log(x % y); // 1

// Increment
console.log(x++); // 7
// x is now 8

// Decrement
console.log(x--); // 8
// x is now 7